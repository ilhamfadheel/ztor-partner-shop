/**
 * The site's languages — the same three a fan can pick as their Ztor default (lib/account.ts), so
 * the account setting and the site always agree. The fan's choice is kept in a cookie the server
 * can read (the session lives only in this browser's localStorage), set when the account loads or
 * changes on /account and when a sign-in completes; without one, the browser's Accept-Language
 * decides. The dictionaries are plain data — no framework — so node's test runner can read them.
 */

export const SITE_LANGS = ["en-us", "zh-hk", "zh-cn"] as const;
export type Lang = (typeof SITE_LANGS)[number];
export const FALLBACK_LANG: Lang = "en-us";
/** Readable by the server on every request; set only by our own JS, so not httpOnly by design. */
export const LANG_COOKIE = "ztor_lang";

/** Exactly one of ours (any case), else null. */
export const asLang = (value: string | null | undefined): Lang | null => {
  const v = value?.trim().toLowerCase();
  return (SITE_LANGS as readonly string[]).includes(v ?? "") ? (v as Lang) : null;
};

/** The best of our languages for an Accept-Language header; null when nothing matches. */
export function langFromAcceptLanguage(header: string | null | undefined): Lang | null {
  if (!header) return null;
  const ranked = header
    .split(",")
    .map((part) => {
      const [tag, ...params] = part.trim().split(";");
      const q = params.map((p) => p.trim()).find((p) => p.startsWith("q="));
      const weight = q ? Number(q.slice(2)) : 1;
      return { tag: tag.trim().toLowerCase(), weight: Number.isFinite(weight) ? weight : 0 };
    })
    .filter((x) => x.tag && x.weight > 0)
    .sort((a, b) => b.weight - a.weight);
  for (const { tag } of ranked) {
    if (tag.startsWith("en")) return "en-us";
    if (tag.startsWith("zh")) {
      // Traditional-script regions read our Hong Kong Chinese; everything else Chinese is simplified.
      return /hant|hk|mo|tw/.test(tag) ? "zh-hk" : "zh-cn";
    }
  }
  return null;
}

/** What goes on <html lang> (BCP 47, the case browsers and translators expect). */
export const htmlLang = (lang: Lang): string => ({ "en-us": "en", "zh-hk": "zh-HK", "zh-cn": "zh-CN" })[lang];

// ---- the cookie, from the browser (the server reads it with next/headers in lib/lang.ts)

export function readLangCookie(): Lang | null {
  if (typeof document === "undefined") return null;
  const pair = document.cookie.split("; ").find((c) => c.startsWith(`${LANG_COOKIE}=`));
  return asLang(pair?.slice(LANG_COOKIE.length + 1));
}

export function storeLangCookie(lang: Lang): void {
  if (typeof document === "undefined") return;
  document.cookie = `${LANG_COOKIE}=${lang}; path=/; max-age=31536000; samesite=lax`;
}

