// Shape-preserving Hermite tangents: continuous velocity, no overshoot at
// plateaus or reversals. Endpoints settle with zero velocity.
const slopes = Object.fromEntries(Object.entries(paths).map(([key, rows]) => [key,
  rows.map((row, i) => [0, ...[1,2,3].map(k => {
    if (!i || i === rows.length - 1) return 0;
    const a = rows[i-1], b = rows[i+1];
    const h0 = row[0]-a[0], h1 = b[0]-row[0];
    const d0 = (row[k]-a[k])/h0, d1 = (b[k]-row[k])/h1;
    if (d0*d1 <= 0) return 0;
    const w0 = 2*h1+h0, w1 = h1+2*h0;
    return (w0+w1)/(w0/d0+w1/d1);
  })]),
]));

export function motionAnchor(key, time) {
  const rows = paths[key], tangents = slopes[key];
  const t = Math.max(rows[0][0], Math.min(rows.at(-1)[0], time));
  let i = 0;
  while (i < rows.length-2 && t > rows[i+1][0]) i++;
  const a=rows[i], b=rows[i+1], h=b[0]-a[0], u=(t-a[0])/h;
  const u2=u*u, u3=u2*u;
  const at = k => (2*u3-3*u2+1)*a[k] + (u3-2*u2+u)*h*tangents[i][k]
    + (-2*u3+3*u2)*b[k] + (u3-u2)*h*tangents[i+1][k];
  return { height: at(1), bottom: at(2), cx: at(3) };
}
